import { jest } from '@jest/globals';
import crypto from 'node:crypto';
import request from 'supertest';
const generate = jest.fn();
jest.unstable_mockModule('@google/genai', () => ({ GoogleGenAI: class { constructor() { this.models = { generateContent: generate }; } } }));
const { default: app } = await import('../src/app.js');
const { User } = await import('../src/models/userModel.js');
const { AiThread } = await import('../src/models/aiThreadModel.js');
const { AiConversation } = await import('../src/models/aiConversationModel.js');
const fixture = async (email = 'chat@test.app') => {
  const user = await User.create({ name: 'Chat athlete', email, passwordHash: 'Password123!', roles: ['athlete'] });
  return { user, headers: { Authorization: `Bearer ${user.generateAccessToken()}` } };
};
beforeEach(() => { generate.mockReset(); generate.mockResolvedValue({ text: JSON.stringify({ answer: 'A useful training answer.' }) }); });
const create = async headers => (await request(app).post('/api/v1/ai/conversations').set(headers).send({})).body.data;
it('imports earlier history once and keeps every conversation private to its owner', async () => {
  const a = await fixture(); const b = await fixture('other@test.app');
  await AiConversation.create({ athleteId: a.user._id, messages: [{ role: 'user', text: 'Earlier question' }] });
  await request(app).get('/api/v1/ai/conversations').set(a.headers);
  const before = (await AiThread.findOne()).updatedAt;
  const list = await request(app).get('/api/v1/ai/conversations').set(a.headers);
  expect(list.body.data.total).toBe(1);
  expect((await AiThread.findOne()).updatedAt).toEqual(before);
  const id = list.body.data.conversations[0]._id;
  const detail = await request(app).get(`/api/v1/ai/conversations/${id}`).set(a.headers);
  expect(detail.body.data.messages[0].text).toBe('Earlier question');
  expect((await request(app).get(`/api/v1/ai/conversations/${id}`).set(b.headers)).status).toBe(404);
  expect((await request(app).patch(`/api/v1/ai/conversations/${id}`).set(b.headers).send({ title: 'Stolen' })).status).toBe(404);
});
it('keeps question and answer history and handles replay without another model call', async () => {
  const { headers } = await fixture(); const thread = await create(headers);
  const body = { conversationId: thread._id, clientRequestId: crypto.randomUUID(), message: 'How should I train today?' };
  const first = await request(app).post('/api/v1/ai/chat').set(headers).send(body);
  expect(first.status).toBe(200);
  const replay = await request(app).post('/api/v1/ai/chat').set(headers).send(body);
  expect(replay.body.data.answer).toBe('A useful training answer.');
  expect(generate).toHaveBeenCalledTimes(1);
  const saved = await AiThread.findById(thread._id);
  expect(saved.messages).toHaveLength(2);
  expect(saved.messages.every(m => m.status === 'complete')).toBe(true);
  expect(saved.title).toBe(body.message);
});
it('saves a question and a pending answer before the provider replies, and rejects a competing turn', async () => {
  const { headers } = await fixture(); const thread = await create(headers);
  let complete; let started;
  const providerStarted = new Promise(resolve => { started = resolve; });
  generate.mockImplementationOnce(() => { started(); return new Promise(resolve => { complete = resolve; }); });
  const pending = request(app).post('/api/v1/ai/chat').set(headers).send({ conversationId: thread._id, clientRequestId: crypto.randomUUID(), message: 'Review my recovery' }).then(r => r);
  await providerStarted;
  const during = await request(app).get(`/api/v1/ai/conversations/${thread._id}`).set(headers);
  expect(during.body.data.messages.map(m => m.status)).toEqual(['complete', 'pending']);
  const competing = await request(app).post('/api/v1/ai/chat').set(headers).send({ conversationId: thread._id, message: 'Second question' });
  expect(competing.status).toBe(409);
  complete({ text: JSON.stringify({ answer: 'Ready.' }) });
  expect((await pending).status).toBe(200);
});
it('retains a failed question and retries that turn without duplicate history', async () => {
  const { headers } = await fixture(); const thread = await create(headers);
  generate.mockRejectedValueOnce(new Error('Provider unavailable'));
  const body = { conversationId: thread._id, clientRequestId: crypto.randomUUID(), message: 'What is my next step?' };
  expect((await request(app).post('/api/v1/ai/chat').set(headers).send(body)).status).toBe(503);
  let saved = await AiThread.findById(thread._id);
  expect(saved.messages[1].status).toBe('failed');
  expect((await request(app).post('/api/v1/ai/chat').set(headers).send(body)).status).toBe(200);
  saved = await AiThread.findById(thread._id);
  expect(saved.messages).toHaveLength(2);
  expect(saved.messages[1].status).toBe('complete');
});
it('supports literal title search, rename and reversible archive without losing messages', async () => {
  const { headers } = await fixture(); const thread = await create(headers);
  await request(app).patch(`/api/v1/ai/conversations/${thread._id}`).set(headers).send({ title: 'Recovery [week 1]' });
  const result = await request(app).get('/api/v1/ai/conversations?q=%5Bweek').set(headers);
  expect(result.body.data.total).toBe(1);
  await request(app).patch(`/api/v1/ai/conversations/${thread._id}`).set(headers).send({ archived: true });
  expect((await request(app).get('/api/v1/ai/conversations').set(headers)).body.data.total).toBe(0);
  expect((await request(app).get('/api/v1/ai/conversations?archived=true').set(headers)).body.data.total).toBe(1);
  expect((await request(app).post('/api/v1/ai/chat').set(headers).send({ conversationId: thread._id, message: 'Hello' })).status).toBe(409);
  await request(app).patch(`/api/v1/ai/conversations/${thread._id}`).set(headers).send({ archived: false });
  expect((await request(app).get('/api/v1/ai/conversations').set(headers)).body.data.total).toBe(1);
});
it('exposes interrupted pending responses as retryable and includes history in account export', async () => {
  const { headers, user } = await fixture();
  const turnId = crypto.randomUUID();
  const thread = await AiThread.create({ athleteId: user._id, activeTurnId: turnId, activeUntil: new Date(Date.now() - 1000), messages: [{ role: 'user', text: 'My question', turnId }, { role: 'assistant', turnId, status: 'pending' }] });
  const result = await request(app).get(`/api/v1/ai/conversations/${thread.id}`).set(headers);
  expect(result.body.data.activeTurnId).toBeUndefined();
  expect(result.body.data.messages[1].status).toBe('failed');
  const exported = await request(app).get('/api/v1/users/me/export').set(headers);
  expect(exported.body.data.conversations[0]._id).toBe(thread.id);
});
